// Build-time StreetForge exporter: turns the auditable text project into a server-side GitHub tree payload.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const output = path.join(root, "server/github/projectSnapshot.generated.ts");
const ignoredDirectories = new Set([".git", ".manus-logs", "dist", "node_modules", "coverage", "uploads", "test-results", "playwright-report"]);
const ignoredFiles = new Set(["server/github/projectSnapshot.generated.ts", ".env", ".env.local"]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = path.relative(root, path.join(directory, entry.name)).split(path.sep).join("/");
    if (ignoredFiles.has(relative) || ignoredDirectories.has(entry.name)) continue;
    if (entry.isDirectory()) files.push(...await walk(path.join(directory, entry.name)));
    else if (entry.isFile()) {
      const content = await readFile(path.join(directory, entry.name), "utf8");
      if (!content.includes("\0")) files.push({ path: relative, content });
    }
  }
  return files;
}

const files = [];
for (const entry of await readdir(root, { withFileTypes: true })) {
  if (ignoredDirectories.has(entry.name) || ignoredFiles.has(entry.name)) continue;
  if (entry.isDirectory()) files.push(...await walk(path.join(root, entry.name)));
  if (entry.isFile()) {
    const content = await readFile(path.join(root, entry.name), "utf8");
    if (!content.includes("\0")) files.push({ path: entry.name, content });
  }
}
files.sort((a, b) => a.path.localeCompare(b.path));
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `// Generated by tools/build-github-snapshot.mjs. Do not edit manually.\nexport type ProjectSnapshotFile = { path: string; content: string };\nexport const projectSnapshot: ProjectSnapshotFile[] = ${JSON.stringify(files)};\n`, "utf8");
console.log(`GitHub snapshot prepared with ${files.length} text files.`);
